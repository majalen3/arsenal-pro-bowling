#!/usr/bin/env node
// Renders the zone tables of docs/ARCHITECTURE_ZONES.md from tools/zones/zones.json (so the doc cannot drift).
//   node tools/zones/zonedoc.mjs           print the generated block
//   node tools/zones/zonedoc.mjs --write   rewrite the block between the markers in docs/ARCHITECTURE_ZONES.md
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadZones, compileZones, ownerOf, trackedFiles } from './lib.mjs';

export const BEGIN = '<!-- zones:begin (generated by tools/zones/zonedoc.mjs; do not edit by hand) -->';
export const END = '<!-- zones:end -->';
const code = a => a.map(x => '`' + x + '`').join(', ');

export function render(cfg = loadZones(), files = trackedFiles()) {
  const out = [];
  out.push('| Zone | Locked | Runs the full suite? | What it is |', '|---|---|---|---|');
  for (const [id, z] of Object.entries(cfg.zones)) out.push(`| **${id}** | ${z.locked && z.locked.length ? 'yes (' + z.locked.length + (z.locked.length === 1 ? ' file)' : ' files)') : ''} | ${z.escalate ? 'yes, any change' : ''} | ${z.title} |`);
  out.push('');
  for (const [id, z] of Object.entries(cfg.zones)) {
    out.push(`#### ${id}${z.locked && z.locked.length ? ' (locked)' : ''}: ${z.title}`, '');
    out.push(`- **Owns:** ${code(z.owns)}`);
    if (z.locked && z.locked.length) out.push(`- **Locked (SHA-256 pinned):** ${code(z.locked)}`);
    out.push(`- **Public interface:** ${z.public && z.public.length ? code(z.public) : 'none (nothing outside imports this zone)'}`);
    if (z.entry && z.entry.length) out.push(`- **Route entries (only the SHELL router imports these):** ${code(z.entry)}`);
    out.push(`- **May import:** ${z.allow && z.allow.length ? z.allow.join(', ') : 'nothing outside the zone'}`);
    const tests = [...(z.extra || []), ...(z.unit || []).map(t => t.replace(/^tests\/data\//, '')), ...(z.browser || []).map(b => cfg.checks[b] ? cfg.checks[b].label : b)];
    out.push(`- **Tests that cover it:** ${tests.length ? tests.map(t => '`' + t + '`').join(', ').replace(/`(Journey [^`]*|Bag ->[^`]*|Spine[^`]*|Add a ball[^`]*|Local recovery[^`]*|Launch foundation[^`]*|Visual[^`]*|engine_equivalence[^`]*)`/g, '$1') : 'none of its own (covered by the full suite)'}`, '');
  }
  out.push('#### Documented exceptions', '', 'Every cross-zone import that breaks a rule today. The boundary check fails on any import that is not in this list, and on any entry here that no longer occurs, so the list can only shrink.', '', '| From | To | Rule | Why it is allowed |', '|---|---|---|---|');
  for (const x of cfg.exceptions) out.push(`| \`${x.from}\` | \`${x.to}\` | ${x.rule} | ${x.reason.replace(/\|/g, '/')} |`);
  return out.join('\n');
}

if (process.argv[1]?.endsWith('zonedoc.mjs')) {
  const block = `${BEGIN}\n${render()}\n${END}`;
  if (process.argv.includes('--write')) {
    const p = path.join(ROOT, 'docs/ARCHITECTURE_ZONES.md'); const md = fs.readFileSync(p, 'utf8');
    const a = md.indexOf(BEGIN), b = md.indexOf(END);
    if (a < 0 || b < 0) { console.error('markers not found'); process.exit(1); }
    fs.writeFileSync(p, md.slice(0, a) + block + md.slice(b + END.length));
    console.log('docs/ARCHITECTURE_ZONES.md updated');
  } else console.log(block);
}
