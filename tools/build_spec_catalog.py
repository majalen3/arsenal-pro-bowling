#!/usr/bin/env python3
"""Build js/data/spec_catalog.js (derived, committed) from the third-party catalogue CSV (NOT committed).

Usage: python3 tools/build_spec_catalog.py /workspace/physics/ball_specs.csv
Source: bowlingballvideos.com ball catalogue as saved in the physics workspace (2026-10-22). Only the derived fields
brand / model / maker condition / cover / core symmetry / RG / diff are emitted; empty cells stay null ("spec TBD").
"""
import csv, json, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else '/workspace/physics/ball_specs.csv'
rows = []
with open(src, newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        brand = (r.get('brand') or '').strip()
        ball = (r.get('ball') or '').strip()
        if not brand or not ball:
            continue
        name = ball[len(brand):].strip() if ball.lower().startswith(brand.lower() + ' ') else ball
        def num(v):
            v = (v or '').strip()
            return float(v) if re.fullmatch(r'\d*\.\d+|\d+', v) else None
        rows.append([brand, name, (r.get('mfr_condition') or '').strip() or None, (r.get('cover') or '').strip() or None,
                     (r.get('core_sym') or '').strip() or None, num(r.get('rg')), num(r.get('diff'))])
rows.sort(key=lambda x: (x[0].lower(), x[1].lower()))
out = ['// GENERATED by tools/build_spec_catalog.py — do not edit by hand. Derived from the bowlingballvideos.com ball catalogue',
       '// (saved 2026-10-22 in the physics workspace; the raw file is not in git). Columns: brand, model, maker condition,',
       '// cover, core symmetry, RG, diff. null = not in the catalogue ("spec TBD"). Shown with a "catalog" chip, never as maker spec.',
       "export const CATALOG_SRC = { kind: 'catalog', ref: 'bowlingballvideos.com catalogue', date: '2026-10-22' };",
       'export const SPEC_ROWS = [']
out += ['  ' + json.dumps(r, ensure_ascii=False) + ',' for r in rows]
out += ['];', '']
open('js/data/spec_catalog.js', 'w', encoding='utf-8').write('\n'.join(out))
print(len(rows), 'rows')
