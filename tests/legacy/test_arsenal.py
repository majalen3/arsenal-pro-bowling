import sys
from playwright.sync_api import sync_playwright
BASE=sys.argv[1]; TAG=sys.argv[2]; fails=[]
def check(c,m):
    print(('PASS ' if c else 'FAIL ')+m)
    if not c: fails.append(m)
with sync_playwright() as p:
    br=p.chromium.launch()
    for name,(w,h,mob) in {'mobile':(390,844,True),'desktop':(1280,800,False)}.items():
        ctx=br.new_context(viewport={'width':w,'height':h},is_mobile=mob,has_touch=mob,device_scale_factor=2 if mob else 1)
        pg=ctx.new_page(); errs=[]
        pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
        pg.on('pageerror',lambda e: errs.append(str(e)))
        pg.goto(BASE); pg.wait_for_timeout(1200)
        check(pg.is_visible('#lane'),f'{name}: lane visible initially')
        pg.click('#tabArsenal'); pg.wait_for_timeout(300)
        check(pg.is_visible('#arsenalView') and not pg.is_visible('#lane'),f'{name}: toggle to Arsenal')
        check(pg.locator('.acard').count()==22,f'{name}: 22 cards ({pg.locator(".acard").count()})')
        check(pg.evaluate('balls.some(b=>b.id=="conspiracy-pearl"&&b.coverName=="Forged 2 Pearl")') and pg.evaluate('balls.every(b=>b.role&&b.oil&&b.oil.length)'),f'{name}: conspiracy + roles/oil on all')
        check(pg.evaluate('document.documentElement.scrollWidth')<=w,f'{name}: no h-overflow arsenal ({pg.evaluate("document.documentElement.scrollWidth")})')
        cols=pg.evaluate('getComputedStyle(document.getElementById("arsGrid")).gridTemplateColumns.split(" ").length')
        check(cols==(1 if mob else 3),f'{name}: grid cols {cols}')
        cb=pg.eval_on_selector('#rgChart','e=>{const r=e.getBoundingClientRect();return [r.width,r.height,r.right]}')
        check(cb[0]>w*0.85 and cb[2]<=w,f'{name}: chart width {cb[0]:.0f}')
        print('  gaps:',pg.text_content('#gapsNote'))
        pg.screenshot(path=f'/workspace/shot_{TAG}_arsenal_{name}_top.png'); pg.screenshot(path=f'/workspace/shot_{TAG}_arsenal_{name}_full.png',full_page=True)
        check(pg.locator('.clshead').count()==11,f'{name}: 11 class headers (default By class)')
        check(pg.locator('#acard-hy-road-40').count()==1 and pg.evaluate('balls.filter(b=>b.rg==null).length')==0 and 'spec TBD' not in pg.text_content('#arsenalView') and 'Columbia 300' in pg.text_content('#acard-green-scout'),f'{name}: no spec TBD left; Scout Reactive (Columbia 300) has specs')
        check(pg.evaluate('ars.pts.length')==22 and not pg.evaluate('ars.pts.some(p=>p.b.rg==null)'),f'{name}: chart has all 22 balls')
        check('League 8.5/10' in pg.text_content('#assess') and 'PAP 5 1/8' in pg.text_content('#assess'),f'{name}: gaps/rating/profile')
        check(pg.locator('.bagball').count()==12,f'{name}: bag builder 12 buttons')
        pg.click('#clsChips .chip:nth-child(2)'); check(pg.locator('.acard').count()==2,f'{name}: class chip filters to 2'); pg.click('#clsChips .chip:nth-child(1)')
        pg.click('#coverChips .chip[data-v=Pearl]'); n=pg.locator('.acard').count()
        check(n==pg.evaluate('balls.filter(b=>b.cover.includes("Pearl")).length') and n>=6,f'{name}: Pearl filter -> {n}')
        pg.click('#coverChips .chip[data-v=All]'); pg.click('#oilChips .chip[data-v=Heavy]'); n=pg.locator('.acard').count()
        check(n==pg.evaluate('balls.filter(b=>b.oil.includes("heavy")).length'),f'{name}: Heavy filter -> {n}')
        pg.click('#oilChips .chip[data-v=All]')
        pg.click('#sortChips .chip[data-v=diff]'); pg.wait_for_timeout(100); d=pg.evaluate('arsList().map(diffOf)')
        check(d==sorted(d,reverse=True),f'{name}: sort diff desc')
        pg.click('#sortChips .chip[data-v=name]'); nm=pg.eval_on_selector_all('.acard h3','e=>e.map(x=>x.textContent)')
        check(nm==sorted(nm,key=lambda x:x.lower()) or nm==sorted(nm),f'{name}: sort name')
        pg.click('#sortChips .chip[data-v=rg]')
        pg.evaluate('document.getElementById("arsGrid").scrollIntoView()')
        pg.click('#compareToggle')
        boxes=pg.locator('.acard .cmp input')
        for i in range(4): boxes.nth(i).check(force=True) if i<3 else boxes.nth(i).set_checked(True,force=True) if False else None
        pg.wait_for_timeout(100)
        for i in range(3): pass
        pg.locator('.acard .cmp input').nth(3).click(force=True)
        check(pg.locator('#compareWrap th').count()>=4 and pg.locator('#compareWrap thead th').count()==4,f'{name}: compare table 3 balls (cap at 3)')
        check(pg.evaluate('document.documentElement.scrollWidth')<=w,f'{name}: no h-overflow compare')
        pg.screenshot(path=f'/workspace/shot_{TAG}_arsenal_{name}_compare.png')
        pg.click('#compareToggle')
        # chart tap
        pos=pg.evaluate('(()=>{const c=document.getElementById("rgChart"),r=c.getBoundingClientRect(),p=ars.pts.find(p=>p.id=="super-nova");return [r.left+p.x/c.width*r.width,r.top+p.y/c.height*r.height]})()')
        pg.evaluate('document.getElementById("rgChart").scrollIntoView()'); 
        pos=pg.evaluate('(()=>{const c=document.getElementById("rgChart"),r=c.getBoundingClientRect(),p=ars.pts.find(p=>p.id=="super-nova");return [r.left+p.x/c.width*r.width,r.top+p.y/c.height*r.height]})()')
        pg.mouse.click(*pos); pg.wait_for_timeout(600)
        check(pg.evaluate('document.getElementById("acard-super-nova").classList.contains("hl")'),f'{name}: chart tap highlights card')
        pg.screenshot(path=f'/workspace/shot_{TAG}_arsenal_{name}_tap.png')
        # info
        pg.locator('#acard-super-nova .info').click(); check(pg.is_visible('#dossierModal.open'),f'{name}: Info opens dossier'); pg.click('.close')
        # put on lane
        pg.locator('#acard-conspiracy-pearl .onlane').click()
        pg.click('#tabArsenal'); pg.locator('.bagball[data-ball=ice-storm]').first.click(); pg.wait_for_timeout(300)
        check(pg.is_visible('#lane') and pg.evaluate('selectedBall.id')=='ice-storm',f'{name}: bag ball -> lane')
        pg.click('#tabArsenal'); pg.locator('#acard-guru-supreme .onlane').click(); pg.wait_for_timeout(300)
        r=pg.evaluate('lastResult'); check(r['endX']<r['startX'] and pg.evaluate('selectedBall.id')=='guru-supreme',f'{name}: TBD ball simulates, hooks left ({r["pocketCall"]})')
        pg.click('#tabArsenal'); pg.locator('#acard-conspiracy-pearl .onlane').click(); pg.wait_for_timeout(500)
        check(pg.is_visible('#lane') and not pg.is_visible('#arsenalView'),f'{name}: back on lane')
        check(pg.evaluate('selectedBall.id')=='conspiracy-pearl' and 'Conspiracy' in pg.text_content('#ballList .ball-card.active'),f'{name}: ball selected')
        r=pg.evaluate('lastResult'); check(r['endX']<r['startX'] and r['points'].__len__()>5 if 'points' in r else r['endX']<r['startX'],f'{name}: conspiracy hooks left, call {r["pocketCall"]}')
        check(pg.evaluate('document.documentElement.scrollWidth')<=w,f'{name}: no h-overflow lane')
        pg.screenshot(path=f'/workspace/shot_{TAG}_arsenal_{name}_lane.png')
        check(not errs,f'{name}: no console errors {errs}')
        ctx.close()
    br.close()
print('FAILS',fails); sys.exit(1 if fails else 0)
